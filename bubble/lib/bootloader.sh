#!/usr/bin/env bash
# shellcheck shell=bash
# bubbleOS bootloader integration (Limine)
#
# The Limine configuration lives on the EFI System Partition, which is mounted
# at $BUBBLEOS_BOOT_DIR. It is rendered from the Btrfs generation layout so the
# boot menu always lists the real generations without embedding state in the
# image.

BUBBLEOS_BOOT_DIR="${BUBBLEOS_BOOT_DIR:-/boot}"
BUBBLEOS_LIMINE_CMDLINE="${BUBBLEOS_LIMINE_CMDLINE:-console=ttyS0,115200 quiet selinux=0}"
# Limine resolves `boot():` paths from the ESP root, which is mounted at
# $BUBBLEOS_BOOT_DIR. The guest therefore sees these files as /boot/vmlinuz.
BUBBLEOS_LIMINE_KERNEL="${BUBBLEOS_LIMINE_KERNEL:-boot():/vmlinuz}"
BUBBLEOS_LIMINE_INITRAMFS="${BUBBLEOS_LIMINE_INITRAMFS:-boot():/initramfs.cpio.gz}"
BUBBLEOS_LIMINE_TIMEOUT="${BUBBLEOS_LIMINE_TIMEOUT:-0}"
# Boot assets shipped inside each generation. They let an old generation boot
# with the kernel and initramfs it was built with after a kernel update.
BUBBLEOS_BOOT_ASSETS_DIR="${BUBBLEOS_BOOT_ASSETS_DIR:-/usr/lib/bubbleos/boot}"
BUBBLEOS_ESP_GENERATIONS_DIR="${BUBBLEOS_ESP_GENERATIONS_DIR:-generations}"

bubble_bootloader_sanitize_title() {
    local value="$1"
    value="${value//$'\n'/ }"
    value="${value//$'\r'/ }"
    value="${value//\//-}"
    printf '%s\n' "${value:0:72}"
}

bubble_bootloader_generations() {
    local dir="$1" entry name
    [[ -d "$dir" ]] || return 0
    for entry in "$dir"/*; do
        [[ -d "$entry" ]] || continue
        name="${entry##*/}"
        [[ "$name" =~ ^[0-9]{6}$ ]] || continue
        printf '%s\n' "$name"
    done | LC_ALL=C sort -r
}

bubble_bootloader_generation_description() {
    local dir="$1" gen="$2" value
    value="$(sed -n 's/^DESCRIPTION=//p' "$dir/$gen/etc/bubbleos/generation" 2>/dev/null | head -n1)"
    [[ -n "$value" ]] || value="bubbleOS generation $gen"
    bubble_bootloader_sanitize_title "$value"
}

bubble_bootloader_cmdline() {
    local root_uuid="$1" extra="${2:-}"
    printf '%s root=UUID=%s rootfstype=btrfs rw' "$BUBBLEOS_LIMINE_CMDLINE" "$root_uuid"
    [[ -z "$extra" ]] || printf ' %s' "$extra"
    printf '\n'
}

# bubble_bootloader_generation_digest <generations-dir> <gen>
#
# Identifies the boot assets carried by a generation. Generations cloned from
# the same system share the digest and can reuse the shared /boot pair.
bubble_bootloader_generation_digest() {
    local generations_dir="$1" gen="$2" assets
    assets="$generations_dir/$gen$BUBBLEOS_BOOT_ASSETS_DIR"
    [[ -f "$assets/vmlinuz" && -f "$assets/initramfs.cpio.gz" ]] || return 1
    # Hash the contents only: cloned generations have the same assets at
    # different paths and must share the staged copies on the ESP.
    cat -- "$assets/vmlinuz" "$assets/initramfs.cpio.gz" | sha256sum |
        cut -d' ' -f1
}

# bubble_bootloader_generation_paths <generations-dir> <gen> [current]
#
# Prints the kernel and initramfs paths for an explicit generation entry. A
# generation whose assets differ from the current one uses private copies on
# the ESP; otherwise the shared /boot pair is reused.
bubble_bootloader_generation_paths() {
    local generations_dir="$1" gen="$2" current="${3:-}"
    local kernel_path="$BUBBLEOS_LIMINE_KERNEL"
    local module_path="$BUBBLEOS_LIMINE_INITRAMFS"
    local digest current_digest

    if [[ -n "$current" && "$gen" != "$current" ]]; then
        if digest="$(bubble_bootloader_generation_digest "$generations_dir" "$gen")"; then
            current_digest="$(
                bubble_bootloader_generation_digest "$generations_dir" "$current" ||
                    true
            )"
            if [[ -z "$current_digest" || "$digest" != "$current_digest" ]]; then
                kernel_path="boot():/$BUBBLEOS_ESP_GENERATIONS_DIR/$gen/vmlinuz"
                module_path="boot():/$BUBBLEOS_ESP_GENERATIONS_DIR/$gen/initramfs.cpio.gz"
            fi
        fi
    fi

    printf '%s\n%s\n' "$kernel_path" "$module_path"
}

# bubble_bootloader_render_config <generations-dir> <root-uuid> [current] [previous]
#
# Entry 1 follows @rootfs/current, so a rollback only needs the symlink update.
# Every other generation gets an explicit rootflags=subvol= entry, which lets
# the operator boot an older generation from the menu without touching the
# current link.
bubble_bootloader_render_config() {
    if [[ -x "${BUBBLEOS_RUST_PATHS_BIN:-}" ]]; then
        bubble_rust_paths bootloader-render "${1:-}" "${2:-}" "${3:-}" "${4:-}"
        return $?
    fi
    local generations_dir="$1" root_uuid="$2" current="${3:-}" previous="${4:-}"
    local gen label description suffix kernel_path module_path

    printf '# Generated by bubbleOS - do not edit by hand.\n'
    printf '# Regenerate with: bubble bootloader sync\n\n'
    printf 'timeout: %s\n' "$BUBBLEOS_LIMINE_TIMEOUT"
    printf 'default_entry: 1\n'
    printf 'serial: yes\n'

    if [[ -n "$current" ]]; then
        label="bubbleOS (current: generation $current)"
    else
        label="bubbleOS (current)"
    fi
    printf '\n/%s\n' "$label"
    printf '    protocol: linux\n'
    printf '    kernel_path: %s\n' "$BUBBLEOS_LIMINE_KERNEL"
    printf '    module_path: %s\n' "$BUBBLEOS_LIMINE_INITRAMFS"
    printf '    cmdline: %s\n' "$(bubble_bootloader_cmdline "$root_uuid")"

    while IFS= read -r gen; do
        [[ -n "$gen" ]] || continue
        [[ "$gen" == "$current" ]] && continue
        description="$(bubble_bootloader_generation_description "$generations_dir" "$gen")"
        suffix=""
        [[ "$gen" == "$previous" ]] && suffix=", previous"
        label="bubbleOS generation $gen${suffix} - $description"
        {
            IFS= read -r kernel_path
            IFS= read -r module_path
        } < <(bubble_bootloader_generation_paths "$generations_dir" "$gen" "$current")
        printf '\n/%s\n' "$label"
        printf '    protocol: linux\n'
        printf '    kernel_path: %s\n' "$kernel_path"
        printf '    module_path: %s\n' "$module_path"
        printf '    cmdline: %s\n' \
            "$(bubble_bootloader_cmdline "$root_uuid" "rootflags=subvol=@rootfs/generations/$gen")"
    done < <(bubble_bootloader_generations "$generations_dir")
}

bubble_bootloader_root_uuid() {
    local source uuid
    uuid="$(findmnt -no UUID -T "$BUBBLEOS_ROOTFS_MOUNT" 2>/dev/null || true)"
    if [[ -z "$uuid" ]]; then
        source="$(findmnt -no SOURCE -T "$BUBBLEOS_ROOTFS_MOUNT" 2>/dev/null || true)"
        source="${source%%[*}"
        [[ -n "$source" ]] || return 1
        uuid="$(blkid -s UUID -o value "$source" 2>/dev/null || true)"
    fi
    [[ -n "$uuid" ]] || return 1
    printf '%s\n' "$uuid"
}

bubble_bootloader_copy_file() {
    local source="$1" destination="$2" temporary
    [[ -f "$source" ]] || return 1
    if [[ -f "$destination" ]] && cmp -s -- "$source" "$destination"; then
        return 0
    fi
    temporary="${destination}.tmp.$$"
    if ! cp -- "$source" "$temporary"; then
        rm -f -- "$temporary"
        return 1
    fi
    chmod 0644 "$temporary" 2>/dev/null || true
    if ! mv -f -- "$temporary" "$destination"; then
        rm -f -- "$temporary"
        return 1
    fi
}

# bubble_bootloader_stage_assets <boot-dir> <generations-dir> [current]
#
# Keeps the shared /boot pair in sync with the current generation and stages
# private assets for generations whose kernel/initramfs differ. Generations
# sharing the current assets keep using the shared pair, which avoids
# duplicating a full kernel and initramfs on every snapshot.
bubble_bootloader_stage_assets() {
    local boot_dir="$1" generations_dir="$2" current="${3:-}"
    local assets_root="$boot_dir/$BUBBLEOS_ESP_GENERATIONS_DIR"
    local gen source target digest current_digest

    if [[ -n "$current" ]]; then
        source="$generations_dir/$current$BUBBLEOS_BOOT_ASSETS_DIR"
        if [[ -f "$source/vmlinuz" && -f "$source/initramfs.cpio.gz" ]]; then
            bubble_bootloader_copy_file "$source/vmlinuz" "$boot_dir/vmlinuz" || {
                printf 'bubble: cannot stage the current kernel on /boot\n' >&2
                return 1
            }
            bubble_bootloader_copy_file \
                "$source/initramfs.cpio.gz" "$boot_dir/initramfs.cpio.gz" || {
                printf 'bubble: cannot stage the current initramfs on /boot\n' >&2
                return 1
            }
        fi
    fi

    current_digest="$(
        bubble_bootloader_generation_digest "$generations_dir" "$current" 2>/dev/null ||
            true
    )"
    install -d -m 0755 "$assets_root" || return 1

    while IFS= read -r gen; do
        [[ -n "$gen" && "$gen" != "$current" ]] || continue
        source="$generations_dir/$gen$BUBBLEOS_BOOT_ASSETS_DIR"
        [[ -f "$source/vmlinuz" && -f "$source/initramfs.cpio.gz" ]] || continue
        digest="$(bubble_bootloader_generation_digest "$generations_dir" "$gen")" ||
            continue
        if [[ -n "$current_digest" && "$digest" == "$current_digest" ]]; then
            continue
        fi
        target="$assets_root/$gen"
        install -d -m 0755 "$target" || return 1
        bubble_bootloader_copy_file "$source/vmlinuz" "$target/vmlinuz" || {
            printf 'bubble: cannot stage the kernel for generation %s\n' "$gen" >&2
            return 1
        }
        bubble_bootloader_copy_file \
            "$source/initramfs.cpio.gz" "$target/initramfs.cpio.gz" || {
            printf 'bubble: cannot stage the initramfs for generation %s\n' "$gen" >&2
            return 1
        }
    done < <(bubble_bootloader_generations "$generations_dir")
}

# bubble_bootloader_prune_assets <boot-dir> <generations-dir> [current]
#
# Drops staged assets that no longer back an explicit entry: removed
# generations, the current generation and generations sharing its assets.
bubble_bootloader_prune_assets() {
    local boot_dir="$1" generations_dir="$2" current="${3:-}"
    local assets_root="$boot_dir/$BUBBLEOS_ESP_GENERATIONS_DIR"
    local entry name digest current_digest

    [[ -d "$assets_root" ]] || return 0
    current_digest="$(
        bubble_bootloader_generation_digest "$generations_dir" "$current" 2>/dev/null ||
            true
    )"
    while IFS= read -r entry; do
        [[ -n "$entry" ]] || continue
        name="${entry##*/}"
        if [[ ! "$name" =~ ^[0-9]{6}$ ]] ||
            [[ "$name" == "$current" ]] ||
            [[ ! -d "$generations_dir/$name" ]]; then
            rm -rf -- "$entry"
            continue
        fi
        digest="$(
            bubble_bootloader_generation_digest "$generations_dir" "$name" 2>/dev/null ||
                true
        )"
        if [[ -z "$digest" ]] ||
            [[ -n "$current_digest" && "$digest" == "$current_digest" ]]; then
            rm -rf -- "$entry"
        fi
    done < <(find "$assets_root" -mindepth 1 -maxdepth 1 -type d 2>/dev/null)
}

# bubble_bootloader_sync
#
# Regenerates /boot/limine.conf from the live generation layout. Safe to call
# when the ESP is not mounted (direct kernel boot): it becomes a no-op so the
# boot is never blocked by an absent boot partition.
bubble_bootloader_sync() {
    local boot_dir="$BUBBLEOS_BOOT_DIR" config tmp uuid current previous

    mountpoint -q "$boot_dir" || return 0
    config="$boot_dir/limine.conf"
    [[ -f "$config" ]] || {
        printf 'bubble: %s not found; skipping Limine update\n' "$config" >&2
        return 1
    }

    uuid="$(bubble_bootloader_root_uuid)" || {
        printf 'bubble: cannot determine the RootFS UUID; skipping Limine update\n' >&2
        return 1
    }
    current="$(bubble_generation_current 2>/dev/null || true)"
    previous="$(bubble_generation_previous 2>/dev/null || true)"

    bubble_bootloader_stage_assets \
        "$boot_dir" "$BUBBLEOS_GENERATIONS_DIR" "$current" || return 1

    tmp="$(mktemp "$boot_dir/.limine.conf.XXXXXX")" || return 1
    if ! bubble_bootloader_render_config \
        "$BUBBLEOS_GENERATIONS_DIR" "$uuid" "$current" "$previous" > "$tmp"; then
        rm -f "$tmp"
        return 1
    fi
    chmod 0644 "$tmp" 2>/dev/null || true
    sync
    if ! mv -f "$tmp" "$config"; then
        rm -f "$tmp"
        return 1
    fi
    if [[ -d "$boot_dir/EFI/BOOT" ]]; then
        cp -f "$config" "$boot_dir/EFI/BOOT/limine.conf"
    fi
    bubble_bootloader_prune_assets \
        "$boot_dir" "$BUBBLEOS_GENERATIONS_DIR" "$current"
    sync

    printf 'bubble: Limine menu updated (%s)\n' "$config"
}
